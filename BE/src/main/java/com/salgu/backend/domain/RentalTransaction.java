package com.salgu.backend.domain;

import jakarta.persistence.Column;
import jakarta.persistence.MappedSuperclass;
import java.math.BigDecimal;
import java.time.LocalDate;
import lombok.Getter;

/** Columns shared by officetel_rentals and multifamily_rentals. Amounts are in 10,000 KRW. */
@Getter
@MappedSuperclass
public abstract class RentalTransaction extends SourceRowEntity {

    private Long recordNo;

    private String regionAddress;

    private String lotAddress;

    private String mainLotNo;

    private String subLotNo;

    private String buildingName;

    private String rentType;

    @Column(name = "exclusive_area_m2")
    private BigDecimal exclusiveAreaM2;

    private String contractYearMonth;

    private Integer contractDay;

    private Long depositManwon;

    private Long monthlyRentManwon;

    private Integer floor;

    private Integer constructionYear;

    private String roadName;

    private String contractPeriod;

    private String contractType;

    private String renewalRightUsed;

    private Long previousDepositManwon;

    private Long previousMonthlyRentManwon;

    @Column(insertable = false, updatable = false) // generated by DB
    private LocalDate contractDate;
}

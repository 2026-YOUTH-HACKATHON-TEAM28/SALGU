package com.salgu.backend.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.Immutable;

@Getter
@Entity
@Immutable
@Table(name = "subway_first_last")
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class SubwayFirstLast extends SourceRowEntity {

    private String lineName;

    private String directionCode;

    private String dayCode;

    private String stationCode;

    private String externalCode;

    private String stationName;

    private String firstTime;

    private String firstOriginCode;

    private String firstDestinationCode;

    private String firstOriginName;

    private String firstDestinationName;

    private String lastTime;

    private String lastOriginCode;

    private String lastDestinationCode;

    private String lastOriginName;

    private String lastDestinationName;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer firstTimeServiceSeconds;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer lastTimeServiceSeconds;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer lineNumber;
}

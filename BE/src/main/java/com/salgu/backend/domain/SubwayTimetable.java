package com.salgu.backend.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.Immutable;

@Getter
@Entity
@Immutable
@Table(name = "subway_timetables")
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class SubwayTimetable extends SourceRowEntity {

    private Long recordNo;

    private String lineCode;

    private String stationCode;

    private String stationName;

    private String dayType;

    private String direction;

    private String expressCode;

    private String trainCode;

    private String arrivalTime;

    private String departureTime;

    private String originStationName;

    private String destinationStationName;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer arrivalTimeServiceSeconds;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer departureTimeServiceSeconds;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer lineNumber;
}

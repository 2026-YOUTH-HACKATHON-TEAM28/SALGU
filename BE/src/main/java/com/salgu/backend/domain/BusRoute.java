package com.salgu.backend.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.Immutable;

@Getter
@Entity
@Immutable
@Table(name = "bus_routes")
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class BusRoute extends SourceRowEntity {

    private String sourceSheet;

    private String companyName;

    private String routeName;

    private String routeType;

    private String originName;

    private String destinationName;

    private BigDecimal authorizedVehicles;

    private BigDecimal headway;

    private BigDecimal distance;

    private BigDecimal operatingDuration;

    private BigDecimal minHeadway;

    private BigDecimal maxHeadway;

    private String firstTime;

    private String lastTime;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer firstTimeServiceSeconds;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer lastTimeServiceSeconds;
}

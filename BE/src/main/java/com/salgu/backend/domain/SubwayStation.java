package com.salgu.backend.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.Immutable;

@Getter
@Entity
@Immutable
@Table(name = "subway_stations")
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class SubwayStation extends SourceRowEntity {

    private String stationCode;

    private String stationName;

    private String stationNameEn;

    private String lineName;

    private String externalCode;

    private String stationNameZh;

    private String stationNameJa;

    @Column(insertable = false, updatable = false) // generated by DB
    private Integer lineNumber;
}
